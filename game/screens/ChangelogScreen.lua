-- ─────────────────────────────────────────────────────────────────────────────
-- 辅助：将一个版本的 items 构建为 UI 节点列表
-- ─────────────────────────────────────────────────────────────────────────────
local function buildVersionItems(items, isLatest)
    local itemNodes = {}
    local borderColor = isLatest and T.Primary or T.Border

    for _, item in ipairs(items) do
        local lineNodes = {}
        for _, line in ipairs(item.lines) do
            if line == "" then
                table.insert(lineNodes, UI.Panel { height = 6 })
            elseif line:sub(1, 1) == "【" then
                table.insert(lineNodes, UI.Label {
                    text      = line,
                    fontSize  = 13,
                    fontColor = T.Primary,
                    fontWeight = "bold",
                    marginTop = 2,
                })
            elseif line:sub(1, 2) == "- " then
                table.insert(lineNodes, UI.Panel {
                    flexDirection = "row",
                    gap = 6,
                    width = "100%",
                    children = {
                        UI.Label { text = "·", fontSize = 13, fontColor = T.Primary },
                        UI.Label {
                            text = line:sub(3),
                            fontSize  = 13,
                            fontColor = T.TextSecondary,
                            flex = 1,
                        },
                    },
                })
            else
                table.insert(lineNodes, UI.Label {
                    text      = line,
                    fontSize  = 13,
                    fontColor = isLatest and T.TextSecondary or T.TextMuted,
                })
            end
        end

        table.insert(itemNodes, UI.Panel {
            width             = "100%",
            paddingVertical   = 10,
            paddingHorizontal = 14,
            marginBottom      = 4,
            backgroundColor   = T.BgCard,
            borderRadius      = 8,
            borderLeftWidth   = 3,
            borderColor       = borderColor,
            gap               = 4,
            children          = (function()
                local rows = {
                    UI.Label {
                        text       = item.title,
                        fontSize   = 15,
                        fontColor  = isLatest and T.TextPrimary or T.TextSecondary,
                        fontWeight = "bold",
                        marginBottom = 4,
                    },
                }
                for _, n in ipairs(lineNodes) do table.insert(rows, n) end
                return rows
            end)(),
        })
    end

    return itemNodes
end

